    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
        // 1. Validar que el campo no esté vacío
        if (txtIdVehicular.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "El Campo de ID del Préstamo es obligatorio");
            return;
        }

        try {
            // 2. Eliminar el préstamo por ID
            ServicioPrestamoVehicular prestamoVehicularService = new ServicioPrestamoVehicular();
            boolean eliminado = prestamoVehicularService.eliminar(Integer.parseInt(txtIdVehicular.getText().trim()));

            if (eliminado) {
                JOptionPane.showMessageDialog(this, "Préstamo Vehicular eliminado exitosamente");
                // Limpiar los campos de texto después de eliminar
                txtMontoPrestamo.setText("");
                txtPlazoPrestamo.setText("");
                txtValorVehiculo.setText("");
                txtMArcaVehiculo.setText("");
                txtPlacaVehiculo.setText("");
                txtIdVehicular.setText("");
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo eliminar el Préstamo Vehicular");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al eliminar: " + e.getMessage());
        }
        
    }//GEN-LAST:event_jButton1ActionPerformed

