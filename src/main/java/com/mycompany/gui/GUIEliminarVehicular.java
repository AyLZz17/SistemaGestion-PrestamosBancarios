    private void btnBuscarEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarEliminarActionPerformed
        
        // 1. Validar que el campo no esté vacío
        if (txtIdVehicular.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "El Campo de ID del Préstamo es obligatorio");
            return;
        }

        try {
            // 2. Buscar el préstamo por ID
            ServicioPrestamoVehicular prestamoVehicularService = new ServicioPrestamoVehicular();
            PrestamoVehicular prestamo = prestamoVehicularService.buscarPorId(Integer.parseInt(txtIdVehicular.getText().trim()));

            if (prestamo != null) {
                // 3. Mostrar los detalles del préstamo en los campos de texto
                TarjetaPropiedad placa = prestamo.getTarjetaPropiedad();
                txtMontoPrestamo.setText(String.valueOf(prestamo.getMonto()));
                txtPlazoPrestamo.setText(String.valueOf(prestamo.getPlazoMeses()));
                txtValorVehiculo.setText(String.valueOf(prestamo.getValorComercial()));
                txtMArcaVehiculo.setText(prestamo.getMarcaVehiculo());
                txtPlacaVehiculo.setText(placa.getPlacaVehiculo());
            } else {
                JOptionPane.showMessageDialog(this, "No se Encontró ese Préstamo Vehicular");
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al buscar: " + e.getMessage());
        }

    }//GEN-LAST:event_btnBuscarEliminarActionPerformed

